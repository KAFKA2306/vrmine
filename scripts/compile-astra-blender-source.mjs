#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";

const [specArg, outArg] = process.argv.slice(2);
if (!specArg || !outArg) {
  console.error("usage: node scripts/compile-astra-blender-source.mjs <config/world-items/*.json> <output-dir>");
  process.exit(2);
}

const root = process.cwd();
const out = path.resolve(root, outArg);
const request = JSON.parse(execFileSync(process.execPath, ["scripts/compile-astra-build-request.mjs", specArg], { cwd: root, encoding: "utf8" }));
const specPath = path.resolve(root, request.source.canonical_spec);
const actualSha = crypto.createHash("sha256").update(fs.readFileSync(specPath)).digest("hex");
if (actualSha !== request.source.sha256) throw new Error("canonical spec changed while compiling Blender source package");

const parameters = {
  schema_version: 1,
  kind: "astra_blender_parameters",
  source: request.source,
  deterministic_seed: request.constraints.deterministic_seed,
  dimensions_m: request.intent.dimensions_m,
  parts: request.intent.parts,
  materials: request.intent.materials,
  license: request.constraints.license,
  generation_method: request.constraints.generation_method,
  generator_authority: "scripts/world_item_factory.py"
};

const wrapper = `# Generated by scripts/compile-astra-blender-source.mjs.\n# Reproducible Blender entry point; do not hand-edit.\nimport hashlib\nimport runpy\nimport sys\nfrom pathlib import Path\n\nROOT = Path(__file__).resolve().parents[3]\nSPEC = ROOT / ${JSON.stringify(request.source.canonical_spec)}\nEXPECTED_SPEC_SHA256 = ${JSON.stringify(request.source.sha256)}\nDETERMINISTIC_SEED = ${request.constraints.deterministic_seed}\n\nactual = hashlib.sha256(SPEC.read_bytes()).hexdigest()\nif actual != EXPECTED_SPEC_SHA256:\n    raise RuntimeError(f\"canonical spec SHA-256 mismatch: {actual}\")\n\nsys.argv = [\"world_item_factory.py\", \"--\", SPEC.relative_to(ROOT).as_posix()]\nrunpy.run_path(str(ROOT / \"scripts/world_item_factory.py\"), run_name=\"__main__\")\n`;

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, "parameters.json"), `${JSON.stringify(parameters, null, 2)}\n`);
fs.writeFileSync(path.join(out, "generate.py"), wrapper);
const files = ["parameters.json", "generate.py"];
const sha256 = Object.fromEntries(files.map((name) => [name, crypto.createHash("sha256").update(fs.readFileSync(path.join(out, name))).digest("hex")]));
fs.writeFileSync(path.join(out, "source-manifest.json"), `${JSON.stringify({ schema_version: 1, kind: "astra_blender_source", source: request.source, deterministic_seed: request.constraints.deterministic_seed, generator_authority: "scripts/world_item_factory.py", artifacts: files, sha256 }, null, 2)}\n`);
