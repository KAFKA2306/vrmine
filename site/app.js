const gateIds = ["g1", "g2", "g3", "g4"];

function normalizeStatus(value) {
  const status = String(value || "PENDING").toUpperCase();
  if (["PASS", "FAIL", "BLOCKED", "PENDING", "MISSING"].includes(status)) return status;
  return "PENDING";
}

function applyStatus(element, status) {
  if (!element) return;
  const normalized = normalizeStatus(status);
  element.textContent = normalized;
  element.classList.remove("pass", "fail", "blocked", "pending", "missing");
  element.classList.add(normalized.toLowerCase());
}

async function loadStatus() {
  const release = document.querySelector("#release-state");
  const summary = document.querySelector("#release-summary");
  const time = document.querySelector("#status-time");

  try {
    const response = await fetch(`status.json?ts=${Date.now()}`, { cache: "no-store" });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const payload = await response.json();
    const releaseStatus = normalizeStatus(payload.release_status);

    release.textContent = releaseStatus;
    release.dataset.state = releaseStatus.toLowerCase();
    const g4Summary = payload.gates?.g4?.summary || "最新のG4証跡を参照してください。";
    summary.textContent = g4Summary.replace(/^Reason:\s*/, "").replace(/^Status:\s*/, "");

    for (const gate of gateIds) {
      const status = normalizeStatus(payload.gates?.[gate]?.status);
      applyStatus(document.querySelector(`#gate-${gate}`), status);
      applyStatus(document.querySelector(`#gate-row-${gate}`), status);
    }

    const generated = payload.generated_at ? new Date(payload.generated_at) : null;
    time.textContent = generated && !Number.isNaN(generated.valueOf())
      ? `Evidence status generated: ${generated.toLocaleString("ja-JP", { timeZone: "Asia/Tokyo" })}`
      : "Evidence status generated by GitHub Pages workflow";
  } catch (error) {
    release.textContent = "UNAVAILABLE";
    release.dataset.state = "fail";
    summary.textContent = "検証ステータスを取得できません。GitHub上の証跡を確認してください。";
    time.textContent = `Status load error: ${error.message}`;
    for (const gate of gateIds) {
      applyStatus(document.querySelector(`#gate-${gate}`), "MISSING");
      applyStatus(document.querySelector(`#gate-row-${gate}`), "MISSING");
    }
  }
}

loadStatus();
